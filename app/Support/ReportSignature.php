<?php

namespace App\Support;

class ReportSignature
{
    public static function generator(): string
    {
        $user = auth()->user();

        return trim((string) $user?->full_name) ?: trim((string) $user?->name);
    }

    public static function csvRows(): array
    {
        return [
            ['', '', ''],
            ['Generated by: '.self::generator(), '', '________________________'],
            ['', '', 'Signature'],
        ];
    }
}
